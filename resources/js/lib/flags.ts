/** The flag picture for a language, or null when there is no fitting one. */
export function flagUrl(code: string): string | null {
    const [lang, region] = code.toLowerCase().split('-');
    const url = (c?: string) => (c ? (FLAG_URLS[`/node_modules/flag-icons/flags/4x3/${c}.svg`] ?? null) : null);
    return url(region?.length === 2 ? region : undefined) ?? url(LANG_COUNTRY[lang]);
}
